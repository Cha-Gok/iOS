        static func buildSections(texts: [String]) -> [TranscriptSection] {
            var result: [TranscriptSection] = []
            var timestamp: TimeInterval = 0
            for text in texts {
                result.append(TranscriptSection(timestamp: timestamp, text: text))
                timestamp += TimeInterval(3 + (text.count % 4))
            }
            return result
        }

